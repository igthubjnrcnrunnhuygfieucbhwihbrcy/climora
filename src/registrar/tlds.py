# Unieke catalogus (dubbele entries gefilterd), gesorteerd op TLD
TLD_CATALOG: dict[str, TldInfo] = {}
for _info in _CATALOG:
    TLD_CATALOG.setdefault(_info.tld, _info)

ALL_TLDS: list[TldInfo] = sorted(TLD_CATALOG.values(), key=lambda i: i.tld)

RESTRICTION_LABELS = {
    Restriction.NONE: "Vrij registreerbaar",
    Restriction.EU_RESIDENCY: "EU-ingezetene of EU-bedrijf vereist",
    Restriction.LOCAL_PRESENCE: "Lokale aanwezigheid vereist",
}


def get_tld(tld: str) -> TldInfo | None:
    return TLD_CATALOG.get(tld.lower().lstrip("."))


def split_domain(name: str) -> tuple[str, str] | None:
    name = name.strip().lower().lstrip(".")
    if "." not in name:
        return None
    label, _, tld = name.rpartition(".")
    if not label or not tld:
        return None
    return label, tld
